function archiveCover(identifier: string): string {
  return `https://archive.org/services/img/${encodeURIComponent(identifier)}`;
}

function archiveMp4(identifier: string, fileName: string): string {
  const encodedFile = fileName
    .split('/')
    .map((part) => encodeURIComponent(part))
    .join('/');
  return `https://archive.org/download/${encodeURIComponent(identifier)}/${encodedFile}`;
}

